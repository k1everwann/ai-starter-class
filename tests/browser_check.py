def inline_html():
    html=(ROOT/'index.html').read_text(encoding='utf-8')
    html=html.replace('<link rel="stylesheet" href="style.css">','<style>'+(ROOT/'style.css').read_text(encoding='utf-8')+'</style>')
    parts=[]
    for n in ['content.js','starter.js','screens.js','app.js']:
        html=html.replace(f'<script src="{n}" defer></script>','')
        parts.append((ROOT/n).read_text(encoding='utf-8').replace('</script','<\\/script'))
    return html.replace('</body>','<script>'+'\n'.join(parts)+'</script></body>')
def route(p,where):
    p.evaluate('(h)=>location.hash=h',where)
    p.wait_for_timeout(100)
